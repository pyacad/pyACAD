"""The committed websites match their sources (python -m unittest discover -s tests/tools).

docs/authoring and docs/tools are generated by tools/build_docs.py and
tools/build_tools_site.py and committed, because Cloudflare Pages serves the folders as
they are, with no build step. A fragment edited without a rebuild would deploy stale
pages, so each builder's --check must pass, and the authoring guide's lint must find
nothing.
"""

import os
import subprocess
import sys
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TOOLS = os.path.join(ROOT, 'tools')


def run(*args):
    return subprocess.run([sys.executable] + list(args), cwd=ROOT,
                          stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          universal_newlines=True, encoding='utf-8')


class GeneratedSitesTests(unittest.TestCase):
    def test_authoring_guide_is_up_to_date(self):
        result = run(os.path.join(TOOLS, 'build_docs.py'), '--check')
        self.assertEqual(result.returncode, 0, result.stdout)

    def test_tools_guide_is_up_to_date(self):
        result = run(os.path.join(TOOLS, 'build_tools_site.py'), '--check')
        self.assertEqual(result.returncode, 0, result.stdout)

    def test_every_site_has_its_headers_file(self):
        for site in ('site', os.path.join('docs', 'authoring'), os.path.join('docs', 'tools')):
            self.assertTrue(os.path.isfile(os.path.join(ROOT, site, '_headers')), site)

    def test_no_control_bytes_in_site_sources(self):
        # An escape mangled on its way into a file (a regex backreference written as
        # byte 1, a backslash-b written as a backspace) still parses, and fails silently.
        roots = [os.path.join(ROOT, 'site'), os.path.join(ROOT, 'docs', 'authoring'),
                 os.path.join(ROOT, 'docs', 'tools')]
        files = [os.path.join(TOOLS, n) for n in ('build_docs.py', 'build_tools_site.py', 'preview.py')]
        for root in roots:
            for folder, _dirs, names in os.walk(root):
                files += [os.path.join(folder, n) for n in names
                          if os.path.splitext(n)[1] in ('.html', '.css', '.js', '.md', '')]
        for path in files:
            with open(path, 'rb') as fh:
                bad = [b for b in fh.read() if b < 32 and b not in (9, 10, 13)]
            self.assertEqual(bad, [], os.path.relpath(path, ROOT))


if __name__ == '__main__':
    unittest.main()
